function translate(text) {
  if (siteLanguage !== "en") return text;
  if (Object.hasOwn(english, text)) return english[text];
  const prefixes = [["Perbesar gambar ", "Enlarge image: "], ["Lihat gambar ", "View image: "]];
  const prefix = prefixes.find(([source]) => text.startsWith(source));
  return prefix ? prefix[1] + translate(text.slice(prefix[0].length).replace(/ dalam ukuran penuh$/, "")) : text;
}

